                {
                    return await next(request, cancellationToken);
                }
            }

            internal class OpenTelemetryPipelineBehavior<TNotification> : IPipelineBehavior<TNotification>
                where TNotification : INotification
            {
                public async Task Handle(TNotification notification, Func<TNotification, CancellationToken, Task> next, CancellationToken cancellationToken)
                {
                    await next(notification, cancellationToken);
                    return;
                }
            }

            #pragma warning restore CS1591
            """);

        ctx.AddSource($"{@namespace}.Extensions.OpenTelemetry.g.cs", sourceBuilder.ToString());
    }
}
