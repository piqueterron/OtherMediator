                public static readonly string[] GeneratedRequestTypes = new[]
                {
            """);

        if (!requestHandlers.IsEmpty)
        {
            var requestNames = requestHandlers
                .Select(h => $"\"{h.Request.Name}\"")
                .Distinct();

            sourceBuilder.AppendLine($"            {string.Join(",\n            ", requestNames)}");
        }

        sourceBuilder.AppendLine($$"""
                };

                public static readonly string[] GeneratedNotificationTypes = new[]
                {
            """);

        if (!notificationHandlers.IsEmpty)
        {
            var notificationNames = notificationHandlers
                .Select(n => $"\"{n.Notification.Name}\"")
                .Distinct();

            sourceBuilder.AppendLine($"            {string.Join(",\n            ", notificationNames)}");
        }

        sourceBuilder.AppendLine($$"""
                };
